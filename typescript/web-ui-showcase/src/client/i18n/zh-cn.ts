export function toolLifecycleLabel(lifecycle: ToolLifecycle): string {
  switch (lifecycle) {
    case "requested": return "已请求";
    case "running": return "执行中";
    case "completed": return "已完成";
    case "failed": return "失败";
  }
}

export function queuedStateLabel(state: "buffered" | "delivered"): string {
  return state === "buffered" ? "等待发送" : "处理中";
}
